    /**
     * Valida los datos del formulario y agrega una estación a la red, junto con
     * las conexiones opcionales que se hayan indicado. Informa al usuario de los
     * errores de validación (campos obligatorios, comas, capacidad no numérica
     * o negativa, conexiones mal escritas o con estaciones inexistentes) y de los
     * identificadores repetidos. Si algo falla no se modifica la red.
     */
    private void agregarEstacion() {
        if (grafo == null) {
            return;
        }
        String id = jTextField2.getText().trim();
        String nombre = jTextField1.getText().trim();
        String linea = jTextField6.getText().trim();
        String zona = jTextField5.getText().trim();
        String textoCapacidad = jTextField4.getText().trim();

        if (id.isEmpty() || nombre.isEmpty()) {
            avisar("El ID y el nombre son obligatorios.");
            return;
        }
        if (id.contains(",") || nombre.contains(",") || linea.contains(",") || zona.contains(",")) {
            avisar("Los campos no pueden contener comas porque se guardan en un archivo CSV.");
            return;
        }
        int capacidad;
        try {
            capacidad = Integer.parseInt(textoCapacidad);
        } catch (NumberFormatException ex) {
            avisar("La capacidad debe ser un número entero.");
            return;
        }
        if (capacidad < 0) {
            avisar("La capacidad no puede ser negativa.");
            return;
        }
        // Las conexiones se validan ANTES de crear la estación, para que un error
        // en ellas no deje la estación agregada a medias.
        String textoConexiones = campoConexiones.getText().trim();
        String[] idsVecinos = new String[0];
        int[] tiempos = new int[0];
        if (!textoConexiones.isEmpty()) {
            String[] pares = textoConexiones.split(";");
            idsVecinos = new String[pares.length];
            tiempos = new int[pares.length];
            for (int i = 0; i < pares.length; i++) {
                String par = pares[i].trim();
                int dosPuntos = par.indexOf(':');
                if (dosPuntos < 0) {
                    avisar("Cada conexión debe escribirse como ID:minutos (se leyó \"" + par + "\").");
                    return;
                }
                String idVecino = par.substring(0, dosPuntos).trim();
                String textoTiempo = par.substring(dosPuntos + 1).trim();
                if (grafo.buscarEstacion(idVecino) == null) {
                    avisar("La estación " + idVecino + " no existe, no se puede conectar con ella.");
                    return;
                }
                if (idVecino.equals(id)) {
                    avisar("Una estación no puede conectarse consigo misma.");
                    return;
                }
                for (int j = 0; j < i; j++) {
                    if (idsVecinos[j].equals(idVecino)) {
                        avisar("La conexión con " + idVecino + " está repetida.");
                        return;
                    }
                }
                try {
                    tiempos[i] = Integer.parseInt(textoTiempo);
                } catch (NumberFormatException ex) {
                    avisar("El tiempo de la conexión con " + idVecino + " debe ser un número entero.");
                    return;
                }
                if (tiempos[i] <= 0) {
                    avisar("El tiempo de la conexión con " + idVecino + " debe ser mayor que 0.");
                    return;
                }
                idsVecinos[i] = idVecino;
            }
        }
        if (!grafo.agregarEstacion(new Estacion(id, nombre, linea, zona, capacidad))) {
            avisar("Ya existe una estación con el ID " + id + ".");
            return;
        }
        // Todas las conexiones ya fueron validadas, así que agregarConexion no debería fallar.
        for (int i = 0; i < idsVecinos.length; i++) {
            grafo.agregarConexion(id, idsVecinos[i], tiempos[i]);
        }
        jTextField1.setText("");
        jTextField2.setText("");
        jTextField4.setText("");
        jTextField5.setText("");
        jTextField6.setText("");
        campoConexiones.setText("");
        informar("Estación " + id + " agregada con " + idsVecinos.length + " conexión(es).");
    }

    /** Cierra temporalmente la estación seleccionada. */
    private void cerrarEstacion() {
        Estacion e = estacionSeleccionada();
        if (e == null) {
            return;
        }
        if (!e.estaActiva()) {
            avisar("La estación " + e.getId() + " ya está cerrada.");
            return;
        }
        grafo.cerrarEstacion(e.getId());
        informar("Estación " + e.getId() + " cerrada.");
    }

    /** Reabre la estación seleccionada. */
    private void reabrirEstacion() {
        Estacion e = estacionSeleccionada();
        if (e == null) {
            return;
        }
        if (e.estaActiva()) {
            avisar("La estación " + e.getId() + " ya está activa.");
            return;
        }
        grafo.reabrirEstacion(e.getId());
        informar("Estación " + e.getId() + " reabierta.");
    }

    /**
     * Elimina la estación seleccionada junto con todas sus conexiones, previa
     * confirmación del usuario.
     */
    private void eliminarEstacion() {
        Estacion e = estacionSeleccionada();
        if (e == null) {
            return;
        }
        String id = e.getId();
        if (!confirmar("Se eliminará la estación " + id + " y todas sus conexiones, "
                + "y desaparecerá del archivo al guardar. ¿Continuar?")) {
            return;
        }
        grafo.eliminarEstacion(id);
        informar("Estación " + id + " eliminada.");
    }

    /**
     * Obtiene la estación seleccionada en la lista desplegable. La posición del
     * elemento elegido coincide con su posición en {@code grafo.getEstaciones()},
     * porque la lista se llena en ese orden.
     *
     * @return la estación seleccionada, o {@code null} si no hay red o no hay
     *         selección (en este último caso se informa al usuario)
     */
    private Estacion estacionSeleccionada() {
        if (grafo == null) {
            return null;
        }
        int posicion = jComboBox1.getSelectedIndex();
        if (posicion < 0) {
            avisar("No hay ninguna estación seleccionada.");
            return null;
        }
        return grafo.getEstaciones().acceder(posicion);
    }

    /**
     * Llena la lista desplegable con las estaciones de la red, en el orden de
     * {@code grafo.getEstaciones()}, y marca las que están cerradas.
     */
    private void llenarListaEstaciones() {
        jComboBox1.removeAllItems();
        Nodo<Estacion> nodo = grafo.getEstaciones().getCabeza();
        while (nodo != null) {
            Estacion e = nodo.getDato();
            jComboBox1.addItem(e.getId() + " - " + e.getNombre() + (e.estaActiva() ? "" : " [CERRADA]"));
            nodo = nodo.getSiguiente();
        }
    }

    /**
     * Muestra el resultado de una operación y actualiza la lista de estaciones y
     * el resumen de la red.
     *
     * @param mensaje descripción del resultado de la operación
     */
    private void informar(String mensaje) {
        llenarListaEstaciones();
        jTextArea1.setText(mensaje + "\n\n" + resumenDeLaRed());
        jTextArea1.setCaretPosition(0);
    }

    /**
     * Construye un resumen de la red: la cantidad de estaciones y de conexiones,
     * el estado y el grado de cada estación, y la lista de conexiones.
     *
     * @return el resumen en texto plano
     */
    private String resumenDeLaRed() {
        StringBuilder sb = new StringBuilder();
        sb.append("Estaciones: ").append(grafo.getNumEstaciones())
          .append("   Conexiones: ").append(grafo.getNumConexiones()).append("\n");

        Nodo<Estacion> nodoE = grafo.getEstaciones().getCabeza();
        while (nodoE != null) {
            Estacion e = nodoE.getDato();
            sb.append("  ").append(e.getId()).append(" - ").append(e.getNombre())
              .append(" [").append(e.getLinea()).append(", ").append(e.getZona()).append("]")
              .append(e.estaActiva() ? "" : " CERRADA")
              .append("  grado ").append(grafo.getGrado(e)).append("\n");
            nodoE = nodoE.getSiguiente();
        }

        sb.append("Conexiones:\n");
        Nodo<Arista> nodoA = grafo.getConexiones().getCabeza();
        while (nodoA != null) {
            Arista a = nodoA.getDato();
            sb.append("  ").append(a.getOrigen().getId()).append(" - ")
              .append(a.getDestino().getId()).append(" (")
              .append(a.getTiempoMin()).append(" min)\n");
            nodoA = nodoA.getSiguiente();
        }
        return sb.toString();
    }

