    /** Títulos de las columnas de la tabla. */
    private static final String[] COLUMNAS = {"ID", "Nombre", "Línea", "Grado", "Hub"};

    /** Red de transporte que se analiza; se asigna con {@link #setGrafo(Grafo)}. */
    private Grafo grafo;

    /**
     * Asigna la red de transporte que analiza el panel y actualiza la tabla.
     *
     * @param grafo red compartida con el resto de los paneles
     */
    public void setGrafo(Grafo grafo) {
        this.grafo = grafo;
        refrescar();
    }

    /**
     * Recalcula el ranking de estaciones por grado y actualiza la tabla. Debe
     * invocarse cada vez que el panel pasa a mostrarse, porque otros paneles
     * pueden haber modificado la red.
     *
     * <p>La tabla lista las estaciones activas de mayor a menor grado. La
     * columna Hub indica las estaciones que tienen el grado máximo.</p>
     */
    public void refrescar() {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(COLUMNAS, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        if (grafo != null) {
            ListaEnlazada<Estacion> hubs = grafo.obtenerHubs();
            Nodo<Estacion> nodo = grafo.obtenerEstacionesPorGrado().getCabeza();
            while (nodo != null) {
                Estacion e = nodo.getDato();
                modelo.addRow(new Object[] {e.getId(), e.getNombre(), e.getLinea(),
                    grafo.getGrado(e), hubs.contiene(e) ? "Sí" : ""});
                nodo = nodo.getSiguiente();
            }
        }
        jTable1.setModel(modelo);
    }

    /** Asocia el botón con la actualización de la tabla y la inicializa vacía. */
    private void configurarEventos() {
        jButton1.addActionListener(evt -> refrescar());
        refrescar();
    }

