    /** Asocia el botón con el análisis y deja el área de resultados de solo lectura. */
    private void configurarEventos() {
        jTextArea1.setEditable(false);
        jTextArea1.setText("Pulse \"Ejecutar Análisis de Conectividad\" para detectar las subredes.");
        jButton1.addActionListener(evt -> ejecutarAnalisis());
    }

    /**
     * Detecta las subredes de la red y muestra para cada una su número, la
     * cantidad de estaciones, la capacidad acumulada y las estaciones que la
     * forman. Indica además las estaciones cerradas, que no participan en el análisis.
     */
    private void ejecutarAnalisis() {
        if (grafo == null) {
            return;
        }
        if (grafo.getNumEstaciones() == 0) {
            jTextArea1.setText("No hay estaciones cargadas.");
            return;
        }
        ListaEnlazada<Subred> subredes = grafo.detectarSubredes();
        StringBuilder sb = new StringBuilder();
        int cerradas = 0;
        Nodo<Estacion> nodoE = grafo.getEstaciones().getCabeza();
        while (nodoE != null) {
            if (!nodoE.getDato().estaActiva()) {
                cerradas++;
            }
            nodoE = nodoE.getSiguiente();
        }

        int total = subredes.getTamano();
        sb.append("Subredes detectadas: ").append(total).append("\n");
        if (total > 1) {
            sb.append("La red está fragmentada: hay zonas que no se comunican entre sí.\n");
        } else if (total == 1) {
            sb.append("Todas las estaciones activas están conectadas entre sí.\n");
        }
        sb.append("\n");

        Nodo<Subred> nodoS = subredes.getCabeza();
        while (nodoS != null) {
            Subred subred = nodoS.getDato();
            sb.append(subred).append("\n  ");
            Nodo<Estacion> nodo = subred.getEstaciones().getCabeza();
            while (nodo != null) {
                sb.append(nodo.getDato().getId());
                nodo = nodo.getSiguiente();
                if (nodo != null) {
                    sb.append(", ");
                }
            }
            sb.append("\n\n");
            nodoS = nodoS.getSiguiente();
        }

        if (cerradas > 0) {
            sb.append("Estaciones cerradas (no participan en el análisis): ").append(cerradas).append("\n  ");
            nodoE = grafo.getEstaciones().getCabeza();
            boolean primera = true;
            while (nodoE != null) {
                if (!nodoE.getDato().estaActiva()) {
                    sb.append(primera ? "" : ", ").append(nodoE.getDato().getId());
                    primera = false;
                }
                nodoE = nodoE.getSiguiente();
            }
            sb.append("\n");
        }
        jTextArea1.setText(sb.toString());
        jTextArea1.setCaretPosition(0);
    }

